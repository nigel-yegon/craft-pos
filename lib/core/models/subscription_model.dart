class PaymentAttemptState {
  static const pending = 'pending';
  static const success = 'success';
  static const failed = 'failed';
  static const timeout = 'timeout';
}

class PaymentAttempt {
  final int id;
  final String? checkoutRequestId;
  final String? merchantRequestId;
  final int amount;
  final String plan;
  final String phone;
  final String state;
  final String? receipt;
  final String? message;
  final DateTime createdAt;
  final DateTime? resolvedAt;

  const PaymentAttempt({
    required this.id,
    this.checkoutRequestId,
    this.merchantRequestId,
    required this.amount,
    required this.plan,
    required this.phone,
    required this.state,
    this.receipt,
    this.message,
    required this.createdAt,
    this.resolvedAt,
  });

  /// Map from the Drift row class generated by `@DataClassName('PaymentAttemptRow')`.
  factory PaymentAttempt.fromRow(PaymentAttemptRow row) => PaymentAttempt(
    id: row.id,
    checkoutRequestId: row.checkoutRequestId,
    merchantRequestId: row.merchantRequestId,
    amount: row.amount,
    plan: row.plan,
    phone: row.phone,
    state: row.state,
    receipt: row.receipt,
    message: row.message,
    createdAt: row.createdAt,
    resolvedAt: row.resolvedAt,
  );

  bool get isPending => state == PaymentAttemptState.pending;
  bool get isSuccess => state == PaymentAttemptState.success;
  bool get isFailed => state == PaymentAttemptState.failed;
  bool get isTimeout => state == PaymentAttemptState.timeout;
  bool get isResolved => !isPending;

  String get amountLabel => 'KSh $amount';

  PaymentAttempt copyWith({
    int? id,
    String? checkoutRequestId,
    String? merchantRequestId,
    int? amount,
    String? plan,
    String? phone,
    String? state,
    String? receipt,
    String? message,
    DateTime? createdAt,
    DateTime? resolvedAt,
  }) {
    return PaymentAttempt(
      id: id ?? this.id,
      checkoutRequestId: checkoutRequestId ?? this.checkoutRequestId,
      merchantRequestId: merchantRequestId ?? this.merchantRequestId,
      amount: amount ?? this.amount,
      plan: plan ?? this.plan,
      phone: phone ?? this.phone,
      state: state ?? this.state,
      receipt: receipt ?? this.receipt,
      message: message ?? this.message,
      createdAt: createdAt ?? this.createdAt,
      resolvedAt: resolvedAt ?? this.resolvedAt,
    );
  }

  @override
  String toString() =>
      'PaymentAttempt(id: $id, plan: $plan, amount: $amount, state: $state, receipt: $receipt)';
}

// ═══════════════════════════════════════════════════════════════════
// COMBINED STATE
// ═══════════════════════════════════════════════════════════════════

class SubscriptionState {
  final SubscriptionModel? active;
  final List<PaymentAttempt> recentAttempts;

  const SubscriptionState({
    required this.active,
    required this.recentAttempts,
  });

  static const empty = SubscriptionState(active: null, recentAttempts: []);

  bool get hasActiveSubscription => active?.isValid ?? false;
  bool get isTrial => active == null;
  bool get isExpiringSoon => active?.isExpiringSoon ?? false;

  PaymentAttempt? get pendingAttempt {
    for (final a in recentAttempts) {
      if (a.isPending) return a;
    }
    return null;
  }

  SubscriptionState copyWith({
    SubscriptionModel? active,
    List<PaymentAttempt>? recentAttempts,
  }) {
    return SubscriptionState(
      active: active ?? this.active,
      recentAttempts: recentAttempts ?? this.recentAttempts,
    );
  }
}