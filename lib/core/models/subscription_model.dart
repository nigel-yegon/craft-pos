class SubscriptionModel {
  final int id;
  final String plan;
  final DateTime startedAt;
  final DateTime expiresAt;
  final bool active;
  final String source;
  final DateTime updatedAt;

  const SubscriptionModel({
    required this.id,
    required this.plan,
    required this.startedAt,
    required this.expiresAt,
    required this.active,
    required this.source,
    required this.updatedAt,
  });

  /// Map from the Drift row class generated by `@DataClassName('SubscriptionRow')`.
  factory SubscriptionModel.fromRow(SubscriptionRow row) => SubscriptionModel(
    id: row.id,
    plan: row.plan,
    startedAt: row.startedAt,
    expiresAt: row.expiresAt,
    active: row.active,
    source: row.source,
    updatedAt: row.updatedAt,
  );

  bool get isValid => active && DateTime.now().isBefore(expiresAt);

  int get daysRemaining {
    if (!isValid) return 0;
    return expiresAt.difference(DateTime.now()).inDays;
  }

  bool get isExpiringSoon => isValid && daysRemaining <= 3;

  String get planTitle => switch (plan) {
    'weekly' => 'Weekly Plan',
    'monthly' => 'Monthly Plan',
    'yearly' => 'Yearly Plan',
    _ => plan,
  };

  String get sourceLabel => switch (source) {
    'mpesa' => 'M-Pesa',
    'code' => 'Activation Code',
    'trial' => 'Free Trial',
    _ => source,
  };

  SubscriptionModel copyWith({
    int? id,
    String? plan,
    DateTime? startedAt,
    DateTime? expiresAt,
    bool? active,
    String? source,
    DateTime? updatedAt,
  }) {
    return SubscriptionModel(
      id: id ?? this.id,
      plan: plan ?? this.plan,
      startedAt: startedAt ?? this.startedAt,
      expiresAt: expiresAt ?? this.expiresAt,
      active: active ?? this.active,
      source: source ?? this.source,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  @override
  String toString() =>
      'SubscriptionModel(plan: $plan, active: $active, expires: $expiresAt, source: $source)';
}

// ═══════════════════════════════════════════════════════════════════
// PAYMENT ATTEMPT
